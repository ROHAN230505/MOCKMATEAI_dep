"""
Transcript and report exports (Section 7.4).

Three formats, three different jobs:

- **TXT transcript** — what the candidate reads back to hear themselves. Plain
  text so it opens anywhere and can be pasted into notes.
- **JSON transcript** — the machine-readable copy: every question, answer,
  per-turn score and the report itself, so nothing in the product is a dead end
  the user can't get their own data out of (Section 12.4's data-ownership
  posture).
- **PDF report** — the shareable artifact from Section 4.11's download button.

Two things every export states plainly, because a document outlives the screen
it was generated from:

1. It is a **practice** report from MockMateAI, not an assessment by any
   employer. A PDF with scores on it will end up in front of other people, and
   it must not be mistakable for an official evaluation.
2. Which categories were **not measured**, and that the narrative was
   deterministic when no model was available. A blank confidence score with no
   explanation invites the reader to assume the worst.
"""
import io
import json
from datetime import datetime

from app.models.enums import FeedbackCategory, FeedbackItemType, InterviewMode
from app.models.feedback import FeedbackReport
from app.models.interview import InterviewSession
from app.services.feedback.prompts import CATEGORY_LABELS
from app.services.feedback.scoring import TurnRecord

DISCLAIMER = (
    "This is a practice interview report generated by MockMateAI. It is not an assessment by any "
    "employer and carries no hiring weight."
)

# What each category would have needed, phrased for a candidate reading a PDF.
UNMEASURED_REQUIREMENTS = {
    FeedbackCategory.CONTENT: "scored answers",
    FeedbackCategory.COMMUNICATION: "a captured transcript",
    FeedbackCategory.CONFIDENCE: "voice-tone analysis",
    FeedbackCategory.BODY_LANGUAGE: "video analysis",
}

# Phase 6. A category can be blank for two quite different reasons, and they are
# not interchangeable. "Not recorded" means something was meant to be measured
# and wasn't — a muted mic, a covered camera. "Not applicable" means the modality
# has no such signal at all: a signed interview has no audio track by design, so
# confidence was never on the table. Told it "needs voice-tone analysis, which
# this session didn't record", a signing candidate would reasonably read a
# deliberate design decision as a fault of theirs to go and fix.
INAPPLICABLE_BY_MODALITY: dict[InterviewMode, set[FeedbackCategory]] = {
    InterviewMode.SIGN: {FeedbackCategory.CONFIDENCE},
}

MODALITY_EXPLANATION = {
    InterviewMode.SIGN: "a signed interview has no audio to measure tone from",
}


def _join(items: list[str]) -> str:
    if len(items) <= 1:
        return items[0] if items else ""
    return f"{', '.join(items[:-1])} and {items[-1]}"


def _sentence_case(text: str) -> str:
    return f"{text[0].upper()}{text[1:]}" if text else text


def unmeasured_note(
    report: FeedbackReport, *, modality: InterviewMode = InterviewMode.VOICE
) -> str | None:
    """
    Which scores are blank on this report, and why each one is.

    Derived from the report row rather than written out. This was a fixed
    sentence -- "this build records no audio prosody or video signal, so
    confidence and body language have no inputs" -- which was true of Phase 4 and
    became false the moment Phase 5's services shipped. A PDF a candidate keeps
    and may show someone is the worst possible place for a stale claim about what
    was measured, so the note reads the scores it is explaining and splits them
    by *why* they are blank (see `INAPPLICABLE_BY_MODALITY`).

    Returns None when everything was measured, in which case there is nothing to
    explain and no note is printed.
    """
    inapplicable = INAPPLICABLE_BY_MODALITY.get(modality, set())

    not_applicable: list[str] = []
    not_recorded: dict[str, str] = {}
    for category, score in (
        (FeedbackCategory.CONTENT, report.content_score),
        (FeedbackCategory.COMMUNICATION, report.communication_score),
        (FeedbackCategory.CONFIDENCE, report.confidence_score),
        (FeedbackCategory.BODY_LANGUAGE, report.body_language_score),
    ):
        if score is not None:
            continue
        label = CATEGORY_LABELS[category].lower()
        if category in inapplicable:
            not_applicable.append(label)
        else:
            not_recorded[label] = UNMEASURED_REQUIREMENTS[category]

    if not not_applicable and not not_recorded:
        return None

    parts = ["Scores shown as — were not measured in this session."]

    if not_recorded:
        labels = _join(list(not_recorded))
        # Order-preserving dedupe: two categories can share a requirement, and
        # "video analysis and video analysis" is not a sentence.
        requirements = _join(list(dict.fromkeys(not_recorded.values())))
        plural = len(not_recorded) > 1
        parts.append(
            f"{_sentence_case(labels)} {'need' if plural else 'needs'} {requirements}, which this "
            f"session did not record, so {'they are' if plural else 'it is'} left blank rather than "
            f"estimated."
        )

    if not_applicable:
        labels = _join(not_applicable)
        plural = len(not_applicable) > 1
        because = MODALITY_EXPLANATION.get(modality, "this interview modality has no such signal")
        parts.append(
            f"{_sentence_case(labels)} {'are' if plural else 'is'} not scored in this format because "
            f"{because}. That is by design, not a gap in this session."
        )

    return " ".join(parts)


DETERMINISTIC_NOTE = (
    "No language model was available when this report was written, so the written analysis is "
    "rule-based. The scores and quoted evidence are real measurements of the session."
)


def _format_score(value: float | None) -> str:
    return "—" if value is None else f"{value:.0f}"


def _format_timestamp(value: datetime | None) -> str:
    return value.strftime("%Y-%m-%d %H:%M UTC") if value else "unknown"


def filename_stem(session: InterviewSession) -> str:
    """A filename a candidate can find again in their downloads folder."""
    role = "".join(ch if ch.isalnum() else "-" for ch in session.role_target.lower()).strip("-")
    role = "-".join(part for part in role.split("-") if part) or "interview"
    date = (session.started_at or session.created_at).strftime("%Y-%m-%d")
    return f"mockmateai-{role}-{date}"


def _turn_lines(turns: list[TurnRecord]) -> list[str]:
    lines: list[str] = []
    for index, turn in enumerate(turns):
        label = "FOLLOW-UP" if turn.is_followup else "QUESTION"
        lines.append("")
        lines.append(f"[Q{index + 1}] {label}: {turn.question_text}")
        if turn.is_skipped:
            lines.append("ANSWER: (skipped — the candidate passed on this question)")
        elif not (turn.transcript_text or "").strip():
            lines.append("ANSWER: (no answer recorded)")
        else:
            lines.append(f"ANSWER: {turn.transcript_text}")
            if turn.relevance_score is not None or turn.completeness_score is not None:
                lines.append(
                    f"SCORED: relevance {turn.relevance_score}/10, completeness {turn.completeness_score}/10"
                )
    return lines


def transcript_text(session: InterviewSession, turns: list[TurnRecord], report: FeedbackReport | None) -> str:
    """The TXT transcript from Section 7.4's `GET /recordings/:sessionId/transcript`."""
    lines: list[str] = [
        "MockMateAI — Interview Transcript",
        "=" * 60,
        f"Role: {session.role_target}",
        f"Type: {session.interview_type.value}",
        f"Started: {_format_timestamp(session.started_at)}",
        f"Ended: {_format_timestamp(session.ended_at)}",
        f"Planned duration: {session.duration_minutes} minutes",
    ]
    if session.target_company_name:
        lines.append(f"Target company: {session.target_company_name}")
    lines.append("")
    lines.append(DISCLAIMER)
    lines.append("=" * 60)
    lines.extend(_turn_lines(turns))

    if report is not None and report.summary_text:
        lines.append("")
        lines.append("-" * 60)
        lines.append("SUMMARY")
        lines.append(report.summary_text)

    lines.append("")
    return "\n".join(lines)


def transcript_json(
    session: InterviewSession, turns: list[TurnRecord], report: FeedbackReport | None
) -> dict:
    """
    The JSON transcript export.

    Includes the report when one exists, so a single download is the complete
    record of the session rather than half of it.
    """
    payload: dict = {
        "session": {
            "id": str(session.id),
            "roleTarget": session.role_target,
            "interviewType": session.interview_type.value,
            "mode": session.mode.value,
            "status": session.status.value,
            "durationMinutes": session.duration_minutes,
            "startedAt": session.started_at.isoformat() if session.started_at else None,
            "endedAt": session.ended_at.isoformat() if session.ended_at else None,
            "targetCompanyName": session.target_company_name,
            "jobDescriptionText": session.job_description_text,
        },
        "disclaimer": DISCLAIMER,
        "turns": [
            {
                "number": index + 1,
                "questionId": turn.question_id,
                "questionText": turn.question_text,
                "questionType": turn.question_type,
                "isFollowup": turn.is_followup,
                "answerText": turn.transcript_text,
                "isSkipped": turn.is_skipped,
                "relevanceScore": turn.relevance_score,
                "completenessScore": turn.completeness_score,
            }
            for index, turn in enumerate(turns)
        ],
    }

    if report is not None:
        payload["report"] = {
            "overallReadinessScore": report.overall_readiness_score,
            "contentScore": report.content_score,
            "communicationScore": report.communication_score,
            "confidenceScore": report.confidence_score,
            "bodyLanguageScore": report.body_language_score,
            "summaryText": report.summary_text,
            "generatedBy": report.generated_by,
            "generatedAt": report.generated_at.isoformat() if report.generated_at else None,
            "items": [
                {
                    "category": detail.category.value,
                    "type": detail.type.value,
                    "text": detail.text,
                    "evidenceReference": detail.evidence_reference,
                }
                for detail in report.details
            ],
        }
    return payload


def transcript_json_bytes(
    session: InterviewSession, turns: list[TurnRecord], report: FeedbackReport | None
) -> bytes:
    return json.dumps(transcript_json(session, turns, report), indent=2, ensure_ascii=False).encode("utf-8")


def report_pdf(
    session: InterviewSession, report: FeedbackReport, turns: list[TurnRecord]
) -> bytes:
    """
    Section 7.4's `GET /feedback/:sessionId/pdf`.

    Built with reportlab's Platypus flowables rather than absolute canvas
    coordinates, so long summaries and long answers paginate on their own
    instead of running off the bottom of page one — a report that silently
    truncates the transcript would be worse than no export.
    """
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        HRFlowable,
        KeepTogether,
        PageBreak,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title=f"MockMateAI feedback report — {session.role_target}",
        author="MockMateAI",
    )

    base = getSampleStyleSheet()
    styles = {
        "title": ParagraphStyle("title", parent=base["Title"], fontSize=20, leading=24, alignment=TA_LEFT),
        "meta": ParagraphStyle("meta", parent=base["Normal"], fontSize=9, leading=13, textColor=colors.HexColor("#555555")),
        "h2": ParagraphStyle("h2", parent=base["Heading2"], fontSize=13, leading=17, spaceBefore=12, spaceAfter=4),
        "body": ParagraphStyle("body", parent=base["Normal"], fontSize=10, leading=15),
        "item": ParagraphStyle("item", parent=base["Normal"], fontSize=10, leading=15, leftIndent=6),
        "evidence": ParagraphStyle(
            "evidence",
            parent=base["Normal"],
            fontSize=9,
            leading=13,
            leftIndent=12,
            textColor=colors.HexColor("#444444"),
            fontName="Helvetica-Oblique",
        ),
        "note": ParagraphStyle("note", parent=base["Normal"], fontSize=8.5, leading=12, textColor=colors.HexColor("#666666")),
        "question": ParagraphStyle("question", parent=base["Normal"], fontSize=10, leading=14, fontName="Helvetica-Bold"),
    }

    def esc(text: str) -> str:
        """Platypus parses a mini-HTML dialect, so candidate text must be escaped."""
        return (text or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    story: list = [
        Paragraph("Interview Feedback Report", styles["title"]),
        Spacer(1, 2 * mm),
        Paragraph(
            f"{esc(session.role_target)} &middot; {esc(session.interview_type.value)} &middot; "
            f"{_format_timestamp(session.started_at)}",
            styles["meta"],
        ),
    ]
    if session.target_company_name:
        story.append(Paragraph(f"Prepared for a role at {esc(session.target_company_name)}", styles["meta"]))
    story.append(Spacer(1, 3 * mm))
    story.append(HRFlowable(width="100%", thickness=0.7, color=colors.HexColor("#cccccc")))

    # --- Scores (Section 10.2) ---
    story.append(Paragraph("Readiness", styles["h2"]))
    score_rows = [
        ["Overall readiness", _format_score(report.overall_readiness_score)],
        [CATEGORY_LABELS[FeedbackCategory.CONTENT], _format_score(report.content_score)],
        [CATEGORY_LABELS[FeedbackCategory.COMMUNICATION], _format_score(report.communication_score)],
        [CATEGORY_LABELS[FeedbackCategory.CONFIDENCE], _format_score(report.confidence_score)],
        [CATEGORY_LABELS[FeedbackCategory.BODY_LANGUAGE], _format_score(report.body_language_score)],
    ]
    table = Table(score_rows, colWidths=[110 * mm, 25 * mm], hAlign="LEFT")
    table.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 10),
                ("ALIGN", (1, 0), (1, -1), "RIGHT"),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("LINEBELOW", (0, 0), (-1, -2), 0.4, colors.HexColor("#e2e2e2")),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f4f4f6")),
            ]
        )
    )
    story.append(table)
    story.append(Spacer(1, 2 * mm))
    note = unmeasured_note(report, modality=session.mode)
    story.append(
        Paragraph("Scores are out of 100." + (f" {note}" if note else ""), styles["note"])
    )

    # --- Summary ---
    if report.summary_text:
        story.append(Paragraph("Summary", styles["h2"]))
        story.append(Paragraph(esc(report.summary_text), styles["body"]))

    # --- Strengths / improvements, grouped so the report reads by theme ---
    for item_type, heading in (
        (FeedbackItemType.STRENGTH, "What worked"),
        (FeedbackItemType.IMPROVEMENT, "What to work on"),
    ):
        matching = [detail for detail in report.details if detail.type == item_type]
        if not matching:
            continue
        story.append(Paragraph(heading, styles["h2"]))
        for detail in matching:
            block = [
                Paragraph(
                    f"<b>{esc(CATEGORY_LABELS[detail.category])}</b> &nbsp;&mdash;&nbsp; {esc(detail.text)}",
                    styles["item"],
                )
            ]
            if detail.evidence_reference:
                block.append(Paragraph(esc(detail.evidence_reference), styles["evidence"]))
            block.append(Spacer(1, 2.5 * mm))
            story.append(KeepTogether(block))

    if report.generated_by and report.generated_by == "deterministic":
        story.append(Spacer(1, 2 * mm))
        story.append(Paragraph(DETERMINISTIC_NOTE, styles["note"]))

    # --- Full transcript, on its own page ---
    story.append(PageBreak())
    story.append(Paragraph("Transcript", styles["h2"]))
    for index, turn in enumerate(turns):
        label = "Follow-up" if turn.is_followup else "Question"
        block = [Paragraph(f"Q{index + 1} &middot; {label}: {esc(turn.question_text)}", styles["question"])]
        if turn.is_skipped:
            block.append(Paragraph("Skipped — you passed on this question.", styles["evidence"]))
        elif not (turn.transcript_text or "").strip():
            block.append(Paragraph("No answer recorded.", styles["evidence"]))
        else:
            block.append(Paragraph(esc(turn.transcript_text), styles["body"]))
            if turn.relevance_score is not None or turn.completeness_score is not None:
                block.append(
                    Paragraph(
                        f"Relevance {turn.relevance_score}/10 &middot; Completeness {turn.completeness_score}/10",
                        styles["evidence"],
                    )
                )
        block.append(Spacer(1, 3 * mm))
        story.append(KeepTogether(block))

    def _footer(canvas, document):
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(colors.HexColor("#777777"))
        canvas.drawString(18 * mm, 11 * mm, DISCLAIMER)
        canvas.drawRightString(A4[0] - 18 * mm, 11 * mm, f"Page {document.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()
